void glcdUpdate()
{
	unsigned char i = 0,j = 0;
	unsigned int uiTempCntr=0;
	lcdSetPage(PAGE1,0);		// initial page, col
		
	for(i = 0; i < 8; i ++)
	{
		for(j = 0; j < 128; j ++)
		{
			lcdWriteData(glcdBuffer[uiTempCntr]);
			uiTempCntr++;
			//delayMs(10);
		}	
		lcdSetPage(PAGE1 + i + 1 , 0);	// increment page
	}
	i=j+1;
	
}
