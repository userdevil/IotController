{
	//delayMs(1);
	LCD_RS	= 1;
	LCD_CS	= 0;	
	LCD_RW	= 0;	
	delay10Us(1);
	//delayMs(1);
	displaySendData(data);	
	delay10Us(1);
	//delayMs(1);
	LCD_RW	= 1;		
	LCD_CS	= 1;
	LCD_RS	= 0;	
	//delayMs(1);
}

void lcdClear(void)
{
	unsigned char i = 0,j = 0;
	
	lcdSetPage(PAGE1,0);		// initial page, col
		
	for(i = 0; i < 8; i ++)
	{
		for(j = 0; j < 128; j ++)
			lcdWriteData(0x00);
	
		lcdSetPage(PAGE1 + i + 1 , 0);	// increment page
	}
	lcdSetPage(PAGE1,0);		// initial page,col
}
void lcdFill(void)
{
	unsigned char i = 0,j = 0;
	
	lcdSetPage(PAGE1,0);		// initial page, col
		
	for(i = 0; i < 8; i ++)
	{
		for(j = 0; j < 128; j ++)
			lcdWriteData(0xff);
	
		lcdSetPage(PAGE1 + i + 1 , 0);	// increment page
	}
	lcdSetPage(PAGE1,0);		// initial page,col
}

void lcdSetPage(unsigned char page,unsigned char col)
{
	unsigned char msb,lsb;
	msb		=	(((col & 0xF0) >> 4)| 0x10);
	lsb		=	(col & 0x0F) ;
	lcdWriteCmd(page);
	lcdWriteCmd(msb);
	lcdWriteCmd(lsb);
}

void displaySendData(unsigned char ucData)
{
	if( (ucData & 0b00000001) == 0)
		LCD_D0=0;
	else
		LCD_D0=1;

	if( (ucData & 0b00000010) == 0)
		LCD_D1=0;
	else
		LCD_D1=1;

	if( (ucData & 0b00000100) == 0)
		LCD_D2=0;
	else
		LCD_D2=1;

	if( (ucData & 0b00001000) == 0)
		LCD_D3=0;
	else
		LCD_D3=1;

	if( (ucData & 0b00010000) == 0)
		LCD_D4=0;
	else
		LCD_D4=1;

	if( (ucData & 0b00100000) == 0)
		LCD_D5=0;
	else
		LCD_D5=1;

	if( (ucData & 0b01000000) == 0)
		LCD_D6=0;
	else
		LCD_D6=1;

	if( (ucData & 0b10000000) == 0)
		LCD_D7=0;
	else
		LCD_D7=1;

}


unsigned char drawDeviceLogo(void)
{
    unsigned int ucX,ucY,uiSource,uiDestination;
    for(uiDestination=0;uiDestination<512;uiDestination++)
        glcdBuffer[uiDestination]=0;
    for(ucY=0;ucY<29;ucY++)
    {
        for(ucX=0;ucX<128;ucX++)
        {
            uiSource=(unsigned int)(ucY*16+(ucX/8));
            if(deviceLogo[uiSource] & (0x80>>(ucX%8)))
            {
                uiDestination=(unsigned int)((ucY/8)*128+ucX);
                glcdBuffer[uiDestination]=(unsigned char)(glcdBuffer[uiDestination] | (1<<(ucY%8)));
            }
        }
    }
    return SUCCESS;
}
