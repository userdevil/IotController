unsigned char glcdWriteChar(unsigned char ucX, unsigned char ucY, unsigned char ucChar,unsigned char ucSize,unsigned char ucPixelStatus)
{

	unsigned int uiJ, uiK;                     // Loop counters
	unsigned char ucPixelData[5];                     // Stores character data
	unsigned char ucTemp=FONT[7];
	if(ucX>21)
		return FAILURE;

	if(ucY>7)
		return FAILURE;

	if(ucSize>3)
		return FAILURE;

	if(ucPixelStatus>1)
		return FAILURE;



	ucX=ucX*6*ucSize;
	if(ucY==1)
		ucY=2;
	else if(ucY==2)
		ucY=13;
	else if(ucY==3)
		ucY=23;
	else if(ucY==4)
		ucY=33;
	else if(ucY==5)
		ucY=43;
	else if(ucY==6)
		ucY=54;

	glcdDrawRectangle(ucX,ucY,ucX+(6*ucSize),ucY+(8*ucSize),YES,!ucPixelStatus);		// the the old character in this space

	/*if(ucChar < 'S') // Checks if the letter is in the first text array
	memcpy(ucPixelData, FONT[ucChar-' '], 5);
	else if(ucChar <= '~') // Check if the letter is in the second array
	memcpy(ucPixelData, FONT2[ucChar-'S'], 5);
	else
	memcpy(ucPixelData, FONT[0], 5);   // Default to space*/

	
	uiK=ucChar-0x20;
	uiK=uiK*5;
	for(uiJ=0;uiJ<5;uiJ++)
	{
		ucPixelData[uiJ]=FONT[uiK+uiJ];
	}
	
	if(ucX+5*ucSize >= GLCD_WIDTH)          // Performs character wrapping
	{
		ucX = 0;                           // Set x at far left position
		ucY += 7*ucSize + 1;                 // Set y at next position down
	}
	for(uiJ=0; uiJ<5; ++uiJ, ucX+=ucSize)         // Loop through character byte data
	{
		for(uiK=0; uiK<7*ucSize; ++uiK)          // Loop through the vertical pixels
		{
			if(bitTest(ucPixelData[uiJ], uiK)) // Check if the pixel should be set
			{
				
                            glcdPixel(ucX,(UINT8) (ucY+uiK),ucPixelStatus); // Draws the pixel
			
			}
                        else
                        {
                               glcdPixel(ucX, (UINT8)(ucY+uiK),!ucPixelStatus); // Draws the pixel
                        }
		}
	}

	return SUCCESS;
}

unsigned char glcdWriteCharCallibri(unsigned char ucX, unsigned char ucY, unsigned char ucChar,unsigned ucFontHeight,unsigned char ucPixelStatus)
{
    unsigned int uiK;                     // Loop counters
    unsigned char ucPixelDataTopRow;                     // Stores character data
    unsigned char ucPixelDataBottomRow;
    unsigned char ucActCharWidth,ucTempF,ucFontNo;
    unsigned int uiStartAddOfFont,uiCntrF;

    ucTempF=0;
    ucFontNo=ucChar-' ';
    uiCntrF=0;
    uiStartAddOfFont = 23*(unsigned int)ucFontNo;
    ucActCharWidth = (UINT8)Calibri11x11[uiStartAddOfFont];
    
//    glcdDrawRectangle(ucX,ucY,ucX+(6*ucFontHeight),ucY+(8*ucFontHeight),YES,!ucPixelStatus);		// the the old character in this space

    
    for(uiCntrF=0;uiCntrF<(ucActCharWidth);uiCntrF++)
    {
        ucPixelDataTopRow=(UINT8)Calibri11x11[uiStartAddOfFont+1+(uiCntrF*2)];
        ucPixelDataBottomRow=(UINT8)Calibri11x11[uiStartAddOfFont+2+(uiCntrF*2)];
       //update top row
        for(uiK=0; uiK<8; ++uiK)          // Loop through the vertical pixels
        {
            if(bitTest(ucPixelDataTopRow, uiK)) // Check if the pixel should be set
            {
                glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK),ucPixelStatus); // Draws the pixel
            }
            else
            {
                glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK),!ucPixelStatus); // Draws the pixel
            }
        }

        //update bottom row
        for(uiK=0; uiK<(15- ucFontHeight); ++uiK)          // Loop through the vertical pixels
        {
            if(bitTest(ucPixelDataBottomRow, uiK)) // Check if the pixel should be set
            {
                glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK+8),ucPixelStatus); // Draws the pixel
            }
            else
            {
                glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK+8),!ucPixelStatus); // Draws the pixel
            }
        }
        
        ucTempF++;
        ucTempPixelAddress++;
    }
    for(uiK=0; uiK<8; ++uiK)          // Loop through the vertical pixels
    {
        glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK),!ucPixelStatus); // Draws the pixel
    }
    for(uiK=0; uiK<(15- ucFontHeight); ++uiK)          // Loop through the vertical pixels
    {
        glcdPixel((UINT8)(ucX+ucTempF),(UINT8)(ucY+uiK+8),!ucPixelStatus); // Draws the pixel
    }
    ucTempPixelAddress++;
    return SUCCESS;
}

