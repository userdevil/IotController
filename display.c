unsigned char glcdDrawLine(unsigned char ucX1,unsigned char ucY1,unsigned char ucX2,unsigned char ucY2,unsigned char ucPixelStatus)
{
    signed int  ix, iy, iaddx, iaddy, idx, idy;
    long lP;
    unsigned int uiCntr;


	if(ucX2>ucX1)
		idx = ((signed int)(ucX2 - ucX1));
	else
		idx = ((signed int)(ucX1 - ucX2));

	if(ucY2>ucY1)
		idy = ((signed int)(ucY2 - ucY1));
	else
		idy = ((signed int)(ucY1 - ucY2));

	ix = ucX1;
	iy = ucY1;

	if(ucX1 > ucX2)
		iaddx = -1;
	else
		iaddx = 1;
	if(ucY1 > ucY2)
		iaddy = -1;
	else
		iaddy = 1;

	if(idx >= idy)
	{
		lP = 2*idy - idx;
		for(uiCntr=0; uiCntr<=idx; ++uiCntr)
		{
			glcdPixel((UINT8)ix, (UINT8)iy, (UINT8)ucPixelStatus);
			if(lP < 0)
			{
				lP += 2*idy;
				ix += iaddx;
			}
			else
			{
				lP += 2*idy - 2*idx;
				ix += iaddx;
				iy += iaddy;
			}
		}
	}
	else
	{
		lP = 2*idx - idy;

		for(uiCntr=0; uiCntr<=idy; ++uiCntr)
		{
			glcdPixel((UINT8)ix, (UINT8)iy, (UINT8)ucPixelStatus);
			if(lP < 0)
			{
				lP += 2*idx;
				iy += iaddy;
			}
			else
			{
				lP += 2*idx - 2*idy;
				ix += iaddx;
				iy += iaddy;
			}
		}
	}
	return SUCCESS;
}


