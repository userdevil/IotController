 void lcdInit(void)
 {
	UINT16 ucCntr=0;
	
	delayMs(150);
	LCD_EN = 1; 
 	LCD_RST	= 0;		                // Clear RST
	delayMs(150);
	LCD_RST	= 1;		                // Set RST
	delayMs(150);
        LCD_CS = 0;

	
	lcdWriteCmd(0xAF); // DISPLAY  ON 
	lcdWriteCmd(0xA0); //	lcdWriteCmd(0xA0); ADC select
	lcdWriteCmd(0xA2); // SET BIAS=1/9
	lcdWriteCmd(0xCF); //	lcdWriteCmd(0xC8); COM SCAN DIRECTION(C63-C0)
	lcdWriteCmd(0x2C); // POWER CONTROL1      boost on
	lcdWriteCmd(0x2E); // POWER CONTROL2      regulator on 110	
	lcdWriteCmd(0x2F); // POWER CONTROL3      follow on
	lcdWriteCmd(0x25); // REGULATOR RESISOR SELECT R2 R1 R0    
	lcdWriteCmd(0x81); // SET REFERENCE VOLTAGE MODE //???
	lcdWriteCmd(0x17); // SET REFERENCE VOLTAGE REGISTER  C5 C4 C3 C2 C1 C0:010111 a=17H   
	lcdWriteCmd(0xA4); // NORMAL DISPLAY   
	lcdWriteCmd(0xA6); // NORMAL DISPLAY     //A6
	lcdWriteCmd(0xB7); // 1st PAGE    
	lcdWriteCmd(0x40); // INITIAL START LINE
	lcdWriteCmd(0x17); // SET COLUMN ADDR (H)   
	lcdWriteCmd(0x01); // SET COLUMN ADDR (L)

	for(ucCntr=0;ucCntr<1024;ucCntr++)
		glcdBuffer[ucCntr]=0x00;
}

 
void lcdWriteCmd(unsigned char cmd)
{
	//delayMs(1);
	LCD_RS	 = 0;
	LCD_CS	 = 0;		
	LCD_RW	 = 0;	
	delay10Us(1);
	//delayMs(1);
	displaySendData(cmd);
	delay10Us(1);
//	delayMs(1);
	LCD_RW	= 1;	
	LCD_CS	= 1;
	LCD_RS	= 1;	
	//delayMs(1);

}
